/**
 * The provider's mark, drawn in `currentColor`.
 *
 * Not the colours the marks ship with: Google's grey (`#C4C6D7`) sits at about
 * 78% lightness and all but disappears on the light theme's white button, and
 * GitHub's black would do the same on the dark one. One asset each, correct on
 * both grounds, because the outline button's foreground is a neutral.
 */
export function ProviderMark({ provider }: { provider: OAuthProviderId }) {
  return provider === "github" ? <GitHubMark /> : <GoogleMark />;
}

