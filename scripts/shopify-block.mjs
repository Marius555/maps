/**
 * Write the theme block for one Shopify app — dev or production — from its
 * template (docs/notes/shopify.md, "Two apps, one block").
 *
 *   node scripts/shopify-block.mjs dev
 *   node scripts/shopify-block.mjs production
 *
 * Run by `npm run shopify:dev`, `shopify:deploy` and `shopify:deploy:production`
 * before the CLI, so it is rarely typed by hand.
 *
 * **Why a template at all.** The block's "Map" picker names the app-owned
 * metaobject type in full, `app--<numeric app id>--map`, because Shopify
 * refuses the `$app:map` shorthand inside a schema (it works in Liquid only,
 * measured 2026-11-02). The dev and production apps are two apps with two ids,
 * but the CLI deploys the one extension folder to whichever app the config
 * names — so a committed id would break the picker on the other app. The
 * template holds `__PINGLIDE_APP_ID__` and `__PINGLIDE_APP_HANDLE__`; the
 * values per app are in distribution/shopify/apps.json.
 *
 * The output, extensions/pinglide-map/blocks/map.liquid, is gitignored: edit
 * distribution/shopify/block-templates/map.liquid instead.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const shopify = fileURLToPath(new URL("../distribution/shopify/", import.meta.url));
const TEMPLATE = `${shopify}block-templates/map.liquid`;
const OUTPUT = `${shopify}extensions/pinglide-map/blocks/map.liquid`;
const APPS = `${shopify}apps.json`;

const name = process.argv[2];
const apps = JSON.parse(readFileSync(APPS, "utf8"));
const app = apps[name];

if (!app) {
  fail(`Name the app: ${Object.keys(apps).join(" or ")} (from distribution/shopify/apps.json).`);
}

if (!/^\d+$/.test(app.appId ?? "")) {
  fail(
    `The ${name} app has no numeric app id in distribution/shopify/apps.json. ` +
      "It is the number in the app's Partner Dashboard URL (…/apps/<id>), not the client id.",
  );
}

if (!/^[a-z0-9][a-z0-9-]*$/.test(app.handle ?? "")) {
  fail(`The ${name} app's handle in distribution/shopify/apps.json is not an app handle: "${app.handle}".`);
}

const template = readFileSync(TEMPLATE, "utf8");
const filled = fillOnce(fillOnce(template, "__PINGLIDE_APP_ID__", app.appId), "__PINGLIDE_APP_HANDLE__", app.handle);

const notice =
  "{%- comment -%}\n" +
  `  GENERATED by scripts/shopify-block.mjs for the ${name} app (${app.config}).\n` +
  "  Edit distribution/shopify/block-templates/map.liquid, never this file.\n" +
  "{%- endcomment -%}\n";

writeFileSync(OUTPUT, notice + filled);
console.log(`[shopify-block] blocks/map.liquid written for the ${name} app (id ${app.appId}, handle ${app.handle}).`);

/** Replace a placeholder that must appear exactly once — a template edit that drops or doubles one fails here, not on a merchant's store. */
function fillOnce(text, placeholder, value) {
  const count = text.split(placeholder).length - 1;
  if (count !== 1) fail(`The block template must hold ${placeholder} exactly once; it holds it ${count} times.`);

  return text.replace(placeholder, value);
}

function fail(message) {
  console.error(`[shopify-block] ${message}`);
  process.exit(1);
}
