/**
 * Builds the vendored list of disposable email domains that `lib/email/disposable.ts`
 * reads.
 *
 * **Why a vendored file rather than a package or an API.** A per-signup call to a
 * verification service would put a paid third party in the path of the one request
 * a stranger makes before they are a customer, and an outage there would be a
 * signup outage. A list costs nothing to consult and cannot go down. The price is
 * that it goes stale between runs of this script, which is why `lib/email/mx.ts`
 * exists alongside it — see `docs/notes/auth.md`.
 *
 * **Licences, checked rather than assumed** (CLAUDE.md §12 — a licence and a demo
 * server's usage policy are different things, and so are a licence and a README):
 *
 * - disposable-email-domains/disposable-email-domains — **CC0 1.0**. Public
 *   domain dedication: copy, modify and use commercially without asking.
 *   Conservative and hand-curated, so it is the half with almost no false
 *   positives.
 * - disposable/disposable-email-domains — **MIT**, © 2017 Andrei Simionescu,
 *   © 2017 Stefan Meinecke, greenSec GmbH. Regenerated daily and an order of
 *   magnitude larger, so it is the half with the coverage.
 *
 * Neither asks for attribution on a rendered page the way GeoNames does; the
 * notice above is the record.
 *
 * Run by hand, never on `prebuild`: it downloads from the network, and its output
 * changes when upstream changes rather than when our code does. Same call
 * `build:gazetteer` makes.
 *
 *     npm run build:disposable-domains
 *
 * Downloads are cached under node_modules/.cache, so a re-run costs nothing.
 * Pass --fresh to ignore the cache.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";

const SOURCES = [
  {
    name: "disposable-email-domains (CC0)",
    url: "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf",
    cache: "curated.conf",
  },
  {
    name: "disposable/disposable-email-domains (MIT)",
    url: "https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains.txt",
    cache: "daily.txt",
  },
];

/**
 * Domains that must never end up on the list, whatever upstream says.
 *
 * The escape hatch with a deploy attached. `EMAIL_DOMAIN_ALLOWLIST` is the one
 * without: reach for that first when a real customer is locked out at 2am, and
 * move the domain here afterwards so the next regeneration does not undo it.
 *
 * Empty today, deliberately — a name here is a claim that upstream is wrong, and
 * inventing those in advance is how a blocklist quietly stops blocking.
 */
const KEEP = [];

const OUT_FILE = join(process.cwd(), "lib", "email", "disposable-domains.generated.ts");
const CACHE_DIR = join(process.cwd(), "node_modules", ".cache", "disposable-domains");

/** The same shape `normalizeDomain` accepts, minus the URL-stripping it does not need. */
const HOSTNAME = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

async function main() {
  const fresh = process.argv.includes("--fresh");
  await mkdir(CACHE_DIR, { recursive: true });

  const domains = new Set();
  const keep = new Set(KEEP);
  let rejected = 0;

  for (const source of SOURCES) {
    const text = await download(source, fresh);
    let added = 0;

    for (const line of text.split("\n")) {
      // Upstream uses `#` for comments in one file and neither uses inline ones.
      const candidate = line.trim().toLowerCase().replace(/\.$/, "");
      if (!candidate || candidate.startsWith("#")) continue;

      // A backtick or a `${` would break out of the template literal this is
      // written into; the hostname rule refuses both, along with the punycode
      // mojibake and stray quoting that a merged list of this size collects.
      if (!HOSTNAME.test(candidate) || candidate.length > 253) {
        rejected += 1;
        continue;
      }

      if (keep.has(candidate)) continue;
      if (!domains.has(candidate)) added += 1;
      domains.add(candidate);
    }

    console.log(`  ${source.name}: ${added} new`);
  }

  // Sorted so a regeneration diffs as "these domains were added" rather than as
  // 90,000 lines of noise nobody can review.
  const sorted = [...domains].sort();

  await writeFile(OUT_FILE, render(sorted), "utf8");

  console.log(
    `\nWrote ${sorted.length} domains to lib/email/disposable-domains.generated.ts` +
      (rejected > 0 ? ` (${rejected} malformed lines dropped)` : ""),
  );
}

function render(domains) {
  const today = new Date().toISOString().slice(0, 10);

  return `/**
 * Generated by \`npm run build:disposable-domains\`. Do not edit by hand.
 *
 * ${domains.length} domains, regenerated ${today}, merged from:
 *   - disposable-email-domains/disposable-email-domains (CC0 1.0)
 *   - disposable/disposable-email-domains (MIT)
 *
 * Sorted, so a regeneration diffs as the domains that were added.
 *
 * **Never import this from anything a browser can reach.** It is a megabyte of
 * string. \`lib/email/disposable.ts\` is the only reader and carries the
 * \`server-only\` guard that makes that a build error rather than a surprise in
 * someone's bundle.
 */
export const DISPOSABLE_DOMAINS = \`${domains.join("\n")}\`;
`;
}

async function download({ name, url, cache }, fresh) {
  const cached = join(CACHE_DIR, cache);

  if (fresh || !existsSync(cached)) {
    process.stdout.write(`  fetching ${cache}… `);
    const response = await fetch(url);

    if (!response.ok) {
      process.stdout.write(`${response.status}\n`);
      throw new Error(`${name} returned ${response.status} — ${url}`);
    }

    await writeFile(cached, Buffer.from(await response.arrayBuffer()));
    process.stdout.write("ok\n");
  }

  return readFile(cached, "utf8");
}

await main();
