/**
 * Builds the land mask the landing page's Europe map draws as dots
 * (components/marketing/europe-map/).
 *
 * **No geography package.** A dot-matrix map needs one bit per grid cell —
 * land or sea — and the Natural Earth raster `npm run mirror:tile-assets`
 * already puts on disk answers exactly that: its sea is near-white and every
 * land colour, ice included, has a channel well under it. So this samples
 * those tiles once and commits the bits; nothing ships but a few kilobytes of
 * text, and nothing runs at view time.
 *
 * Run by hand, after `npm run mirror:tile-assets`:
 *
 *     npm run build:world-dots
 *
 * Output: lib/marketing/world-dots.data.ts. Rows run north to south, columns
 * west to east, six cells to a character (see `ALPHABET`, which
 * lib/marketing/world-dots.ts decodes with).
 */

import sharp from "sharp";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";

const TILES = join("public", "tiles", "natural_earth", "ne2sr");
const ZOOM = 3;
const OUT = join("lib", "marketing", "world-dots.data.ts");

/** Six bits to a character; URL-safe, and no character JS needs escaped. */
const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

/** Web Mercator's own edge; rows past it have no picture to sample. */
const MERCATOR_LAT = 85;

/** Any channel this dark or darker is land. The sea measures 245 and up, the Baltic 238. */
const LAND_BELOW = 236;

/** Samples per cell side, and the share of them that must be land. */
const SAMPLES = 4;
const LAND_SHARE = 0.35;

const GRIDS = [
  { name: "europe", step: 0.5, west: -12, east: 35, south: 35, north: 62 },
];

if (!existsSync(join(TILES, String(ZOOM)))) {
  console.error(`No Natural Earth tiles at ${TILES}/${ZOOM}. Run npm run mirror:tile-assets first.`);
  process.exit(1);
}

const tileCache = new Map();

async function tile(x, y) {
  const key = `${x}/${y}`;
  if (!tileCache.has(key)) {
    const file = join(TILES, String(ZOOM), String(x), `${y}.png`);
    tileCache.set(
      key,
      sharp(file)
        .ensureAlpha()
        .raw()
        .toBuffer({ resolveWithObject: true }),
    );
  }
  return tileCache.get(key);
}

async function isLandAt(lng, lat) {
  const tiles = 2 ** ZOOM;
  const rad = (lat * Math.PI) / 180;
  const fx = ((lng + 180) / 360) * tiles;
  const fy = ((1 - Math.log(Math.tan(rad) + 1 / Math.cos(rad)) / Math.PI) / 2) * tiles;
  const tx = Math.min(tiles - 1, Math.max(0, Math.floor(fx)));
  const ty = Math.min(tiles - 1, Math.max(0, Math.floor(fy)));

  const { data, info } = await tile(tx, ty);
  const px = Math.min(info.width - 1, Math.floor((fx - tx) * info.width));
  const py = Math.min(info.height - 1, Math.floor((fy - ty) * info.height));
  const i = (py * info.width + px) * info.channels;
  return data[i] < LAND_BELOW || data[i + 1] < LAND_BELOW || data[i + 2] < LAND_BELOW;
}

async function isLandCell(west, north, step) {
  let land = 0;
  let total = 0;
  for (let sy = 0; sy < SAMPLES; sy++) {
    for (let sx = 0; sx < SAMPLES; sx++) {
      const lng = west + ((sx + 0.5) / SAMPLES) * step;
      const lat = north - ((sy + 0.5) / SAMPLES) * step;
      if (Math.abs(lat) > MERCATOR_LAT) continue;
      total++;
      if (await isLandAt(lng, lat)) land++;
    }
  }
  return total > 0 && land / total >= LAND_SHARE;
}

function encodeRow(bits) {
  let out = "";
  for (let i = 0; i < bits.length; i += 6) {
    let value = 0;
    for (let b = 0; b < 6; b++) value = (value << 1) | (bits[i + b] ? 1 : 0);
    out += ALPHABET[value];
  }
  return out;
}

async function buildGrid({ name, step, west, east, south, north }) {
  const cols = Math.round((east - west) / step);
  const rows = Math.round((north - south) / step);
  const encoded = [];
  let count = 0;

  for (let r = 0; r < rows; r++) {
    const bits = [];
    for (let c = 0; c < cols; c++) {
      const land = await isLandCell(west + c * step, north - r * step, step);
      bits.push(land);
      if (land) count++;
    }
    encoded.push(encodeRow(bits));
  }

  console.log(`${name}: ${cols}×${rows} cells, ${count} land`);
  return { name, step, west, north, cols, rows, encoded };
}

const grids = [];
for (const grid of GRIDS) grids.push(await buildGrid(grid));

const body = grids
  .map(
    (g) => `  ${g.name}: {
    step: ${g.step},
    west: ${g.west},
    north: ${g.north},
    cols: ${g.cols},
    rows: [
${g.encoded.map((row) => `      "${row}",`).join("\n")}
    ],
  },`,
  )
  .join("\n");

const source = `// Generated by scripts/build-world-dots.mjs from the Natural Earth raster.
// Do not edit by hand; re-run \`npm run build:world-dots\`.

export const WORLD_DOT_GRIDS = {
${body}
} as const;
`;

await writeFile(OUT, source);
console.log(`Wrote ${OUT}`);
